# -*- coding: utf-8 -*-
"""
Подбор темы по тексту сообщения.

Модуль намеренно не знает ничего про Telegram и не имеет зависимостей —
поэтому его можно запускать и проверять без токена: `python3 test_router.py`.

Как устроено. Текст приводится к нижнему регистру, «ё» заменяется на «е»,
пунктуация выкидывается. Дальше по списку тем ищется первое совпадение:
  • ключ с пробелом ищется как подстрока целиком («сколько стоит»);
  • ключ без пробела считается началом слова, причём «интернет-магазин»
    разбивается на два слова — иначе ключ «магазин» до него не достанет.

Второе важно. Если искать «бот» подстрокой, то слово «работа» тоже совпадёт —
и вопрос «как у вас построена работа» уедет в ответ про чат-ботов. Сравнение
по началу слова это исключает: «работа».startswith("бот") — ложь.
"""

import re

_PUNCT = re.compile(r"[^\w\s-]", flags=re.UNICODE)

# Порядок важен: побеждает первое совпадение, поэтому узкие темы идут выше широких.
INTENTS = [
    # Явная просьба оставить заявку — раньше всего, чтобы не перехватили «сайт» или «цена».
    ("brief", (
        "заявк", "оставить заявку", "хочу заказать", "хочу заказ", "заказать сайт",
        "обсудить проект", "давайте начнем", "готов начать", "начать работу",
    )),
    ("greeting", ("привет", "здравств", "добрый день", "доброе утро", "добрый вечер", "салют")),
    ("thanks", ("спасибо", "благодар", "спс")),

    ("price", (
        "сколько стоит", "сколько будет стоить", "во сколько обойдется",
        "цен", "стоимост", "стои", "прайс", "бюджет", "смет", "дорого", "дешев",
    )),
    ("terms", (
        "как долго", "сколько времени", "сколько ждать", "как быстро",
        "срок", "успее", "когда будет готов", "за сколько сделаете",
    )),
    ("bots", ("бот", "чатбот", "чат-бот", "телеграм бот", "автоответчик")),

    # «как работаете» — это про процесс; ставим выше портфолио, где есть слово «работы».
    ("process", (
        "как вы работаете", "как работаете", "как происходит", "как проходит",
        "этап", "процесс", "с чего начать", "что от меня нужно", "шаг",
    )),
    ("conditions", (
        "услови", "договор", "гаранти", "предоплат", "аванс",
        "правк", "исходник", "доступ", "не понравится", "не устроит", "не подойдет",
    )),
    ("work", (
        "портфолио", "кейс", "пример работ", "примеры", "что делали",
        "ниш", "стоматолог", "клиник", "строит", "стройк", "застройщик",
        "школ", "учебн", "образован",
    )),
    ("services", (
        "услуг", "что вы делаете", "что делаете", "что умеешь", "чем занимаетесь",
        "лендинг", "магазин", "корпоративн", "редизайн", "поддержк", "сайт",
    )),
    ("contacts", (
        "контакт", "связаться", "живой человек", "человек", "менеджер",
        "позвонить", "телефон", "почт", "инстаграм", "instagram", "оператор",
    )),
]


def normalize(text: str) -> str:
    """Нижний регистр, «ё» → «е», долой пунктуацию."""
    text = (text or "").lower().replace("ё", "е")
    return _PUNCT.sub(" ", text)


def match(text: str):
    """Возвращает ключ темы или None, если ничего не подошло."""
    clean = normalize(text)
    if not clean.strip():
        return None

    # дефис — тоже граница слова: «интернет-магазин» → «интернет», «магазин»
    words = clean.replace("-", " ").split()
    for key, keywords in INTENTS:
        for kw in keywords:
            if " " in kw:
                if kw in clean:
                    return key
            elif any(word.startswith(kw) for word in words):
                return key
    return None
